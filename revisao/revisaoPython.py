    #2. Operadores
# Operadores são símbolos ou palavras que realizam operações.
# Tipos:
        # Aritméticos:
# +	Soma	5 + 3 → 8
# -	Subtração	5 - 3 → 2
# *	Multiplicação	5 * 3 → 15
# /	Divisão	6 / 2 → 3.0
# //	Divisão inteira	7 // 2 → 3
# %	Resto da divisão	7 % 2 → 1
# **	Potência	2 ** 3 → 8

       # Comparação:
# ==	Igual a
# !=	Diferente de
# >	Maior que
# <	Menor que
# >=	Maior ou igual a
#<=	Menor ou igual a

# operadores lógicos:
# and	Verdadeiro se as duas condições forem verdadeiras
# or	Verdadeiro se pelo menos uma condição for verdadeira
# not	Inverte o resultado (True vira False e vice-versa)


